type LocaleContextValue = {
  language: AppLanguage;
  setLanguage: (language: AppLanguage) => Promise<void>;
  t: (slovak: string) => string;
  errorText: (message: string) => string;
};

const LocaleContext = createContext<LocaleContextValue | null>(null);

export function LocaleProvider({ children }: { children: ReactNode }) {
  const AsyncStorage = useAppStorage();
  const [language, setLanguageState] = useState<AppLanguage>('sk');
  const hasSelectedLanguage = useRef(false);

  useEffect(() => {
    let active = true;
    AsyncStorage.getItem(STORAGE_KEY).then((saved) => {
      if (active && !hasSelectedLanguage.current && (saved === 'sk' || saved === 'en')) {
        setLanguageState(saved);
      }
    }).catch((error: unknown) => {
      console.warn('Could not load language preference:', error);
      Alert.alert(translateText('Jazyk', language, englishTranslations), localizedError(error instanceof Error ? error.message : String(error), language));
    });
    return () => {
      active = false;
    };
  }, []);

  const setLanguage = useCallback(async (nextLanguage: AppLanguage) => {
    hasSelectedLanguage.current = true;
    setLanguageState(nextLanguage);
    try {
      await AsyncStorage.setItem(STORAGE_KEY, nextLanguage);
    } catch (error) {
      throw error;
    }
  }, []);

  const value = useMemo<LocaleContextValue>(() => ({
    language,
    setLanguage,
    t: (slovak) => translateText(slovak, language, englishTranslations),
    errorText: (message) => {
      if (!Object.hasOwn(englishTranslations, message) && !Object.values(englishTranslations).includes(message)) {
        console.warn('Application error:', message);
      }
      return translateError(message, language, englishTranslations);
    },
  }), [language, setLanguage]);

  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>;
}

export function useLocale() {
  const value = useContext(LocaleContext);
  if (!value) throw new Error('useLocale must be used within LocaleProvider.');
  return value;
}
